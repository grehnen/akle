// bun run schedule:extend [--dry-run] [--now <ISO date>]
// The quarterly cron (ADR 0001). Under `extendBelowDays` days left, it regenerates the schedule from
// HEAD on the extension branch and opens the extension PR, or updates its own open one. A
// hand-edited extension PR is never regenerated: the cron only comments on it. Under
// `autoMergeBelowDays` days left, it also turns on auto-merge (thresholds in
// src/schedule/runway.ts). --dry-run only looks up the open PR and prints what it would do.
// Needs APP_SLUG, the GitHub App it runs as: only that App's PRs from this repo count as its own.
import { autoMergeBelowDays, extensionPlan, runwayDays } from "../src/schedule/runway";
import { type OpenPullRequest, findExtensionPullRequest } from "./extensionPullRequest";
import { argument, git, readScheduleConfig, readScheduleRows, run } from "./scheduleData";

const extensionBranch = "schedule/extend";
const baseBranch = "main";
const title = "🗃️ Extend the schedule";

const dryRun = Bun.argv.includes("--dry-run");
const nowArgument = argument("now");
const now = new Date(nowArgument ?? Date.now());
const appSlug = requiredEnv("APP_SLUG");

const days = runwayDays(await readScheduleRows(), now, (await readScheduleConfig()).epoch);
const plan = extensionPlan(days, findExtensionPullRequest(openPullRequests(), appSlug));

console.log(`${days} days of puzzles left.`);
if (plan.action === "none") {
  console.log("Runway is long enough; nothing to do.");
  process.exit(0);
}
const target =
  plan.action === "open"
    ? "Open an extension PR"
    : plan.action === "update"
      ? `Update extension PR #${plan.pullRequest}`
      : `Comment on hand-edited extension PR #${plan.pullRequest}`;
console.log(
  `${dryRun ? "Would: " : ""}${target} from ${extensionBranch}, auto-merge ${plan.autoMerge ? "on" : "off"}.`,
);
if (dryRun) process.exit(0);

const autoMergeNote = plan.autoMerge
  ? "on: the PR merges once the checks pass"
  : `off until fewer than ${autoMergeBelowDays} days are left`;

let pullRequest: string;
if (plan.action === "comment") {
  pullRequest = String(plan.pullRequest);
  const comment = `The schedule needs extending: ${days} days of puzzles were left when this ran. This PR has commits not made by the extension cron, so it was not regenerated and the hand edits were preserved. Extend it by hand with \`bun run schedule\` if it doesn't add enough days. Auto-merge is ${autoMergeNote}.`;
  run(["gh", "pr", "comment", pullRequest, "--body-file", "-"], comment);
} else {
  git(["switch", "--force-create", extensionBranch]);
  const report = run([
    "bun",
    "scripts/schedule.ts",
    ...(nowArgument ? ["--now", nowArgument] : []),
  ]);
  git(["add", "data/schedule/"]);
  git(["commit", "--message", title]);
  git(["push", "--force", "origin", extensionBranch]);

  const body = `${days} days of puzzles were left when this ran. Auto-merge is ${autoMergeNote}. Generated by \`bun run schedule:extend\`; unplayed rows may be curated by hand before merging, and the cron then leaves the PR as it is.\n\n${report}`;
  if (plan.action === "open") {
    pullRequest = run(
      [
        "gh",
        "pr",
        "create",
        "--base",
        baseBranch,
        "--head",
        extensionBranch,
        "--title",
        title,
        "--body-file",
        "-",
      ],
      body,
    ).trim();
  } else {
    pullRequest = String(plan.pullRequest);
    run(["gh", "pr", "edit", pullRequest, "--title", title, "--body-file", "-"], body);
  }
}
if (plan.autoMerge) run(["gh", "pr", "merge", pullRequest, "--auto", "--rebase"]);
console.log(`${target}: ${pullRequest}`);

/** The open PRs from a branch named like the extension branch, in this repo or a fork. */
function openPullRequests(): OpenPullRequest[] {
  return JSON.parse(
    run([
      "gh",
      "pr",
      "list",
      "--head",
      extensionBranch,
      "--base",
      baseBranch,
      "--state",
      "open",
      "--json",
      "number,isCrossRepository,author,commits",
    ]),
  );
}

function requiredEnv(name: string): string {
  const value = process.env[name];
  if (!value) throw new Error(`${name} must be set`);
  return value;
}
