// bun run schedule:extend [--dry-run] [--now <ISO date>]
// The monthly cron (ADR 0001). Under 90 days left, it regenerates the schedule from HEAD on the
// extension branch and opens the extension PR, or updates its own open one. Under 40 days, it
// also turns on auto-merge. --dry-run only looks up the open PR and prints what it would do.
import { extensionPlan, runwayDays } from "../src/schedule/runway";
import { argument, git, readScheduleConfig, readScheduleRows } from "./scheduleData";

const extensionBranch = "schedule/extend";
const baseBranch = "main";
const title = "🗃️ Extend the schedule";

const dryRun = Bun.argv.includes("--dry-run");
const nowArgument = argument("now");
const now = new Date(nowArgument ?? Date.now());

const days = runwayDays(await readScheduleRows(), now, (await readScheduleConfig()).epoch);
const openPullRequest = findOpenPullRequest();
const plan = extensionPlan(days, openPullRequest);

console.log(`${days} days of puzzles left.`);
if (plan.action === "none") {
  console.log("Runway is long enough; nothing to do.");
  process.exit(0);
}
const target =
  plan.action === "open" ? "Open an extension PR" : `Update extension PR #${plan.pullRequest}`;
console.log(
  `${dryRun ? "Would: " : ""}${target} from ${extensionBranch}, auto-merge ${plan.autoMerge ? "on" : "off"}.`,
);
if (dryRun) process.exit(0);

git(["switch", "--force-create", extensionBranch]);
const report = run(["bun", "scripts/schedule.ts", ...(nowArgument ? ["--now", nowArgument] : [])]);
git(["add", "data/schedule/"]);
git(["commit", "--message", title]);
git(["push", "--force", "origin", extensionBranch]);

const body = `${days} days of puzzles were left when this ran. Auto-merge is ${plan.autoMerge ? "on: the PR merges once the checks pass" : "off until fewer than 40 days are left"}. Generated by \`bun run schedule:extend\`; unplayed rows may be curated by hand before merging.\n\n${report}`;
const pullRequest =
  plan.action === "open"
    ? run(
        [
          "gh",
          "pr",
          "create",
          "--base",
          baseBranch,
          "--head",
          extensionBranch,
          "--title",
          title,
          "--body-file",
          "-",
        ],
        body,
      ).trim()
    : String(plan.pullRequest);
if (plan.action === "update") {
  run(["gh", "pr", "edit", pullRequest, "--title", title, "--body-file", "-"], body);
}
if (plan.autoMerge) run(["gh", "pr", "merge", pullRequest, "--auto", "--rebase"]);
console.log(`${target}: ${pullRequest}`);

/** The number of the open PR from the extension branch, if any. */
function findOpenPullRequest(): number | undefined {
  const output = run([
    "gh",
    "pr",
    "list",
    "--head",
    extensionBranch,
    "--base",
    baseBranch,
    "--state",
    "open",
    "--json",
    "number",
    "--jq",
    ".[].number",
  ]).trim();
  return output === "" ? undefined : Number(output.split("\n")[0]);
}

function run(command: string[], stdin?: string): string {
  const result = Bun.spawnSync(command, {
    stdin: stdin === undefined ? "ignore" : new TextEncoder().encode(stdin),
    stderr: "pipe",
  });
  if (result.exitCode !== 0) {
    throw new Error(`${command.join(" ")} failed: ${result.stderr.toString()}`);
  }
  return result.stdout.toString();
}
